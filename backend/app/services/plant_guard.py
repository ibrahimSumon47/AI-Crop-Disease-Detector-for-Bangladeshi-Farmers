"""
Pre-inference sanity gate: refuse obvious NON-leaf photos before they reach
the disease ONNX model, and warn about photo quality (blur / darkness).

Why: with a 61-class model, any random photo (a sprouted potato on white,
a product shot, a flat color image) still produces a softmax answer — e.g.
"2% cauliflower insect holes" — which the UI would render as misleading
low-confidence advice. Serving an answer to a photo that contains no plant
material is worse than refusing.

Two layers:

1. TRAINED GATE (primary): a tiny GradientBoosting classifier (19
   hand-crafted color/texture features, trained on real leaves from all 61
   classes + synthetic photo-junk negatives) exported to
   app/data/plant_guard_model.onnx and served with the same onnxruntime the
   disease model uses. It generalizes much further than any hand rule:
   leaves on dark PlantVillage backgrounds, washed-out field photos and
   "blob on plain card" product shots were all used in training. Honest
   measured numbers live in ml/reports/plant_classifier_metrics.json
   (regenerated by ml/src/evaluate_plant_gate.py); the serving threshold
   below was picked to keep REAL-leaf rejection under ~1%.

2. CHEAP PRE-SCREEN (kept from the v1 heuristic): a flat/blank image has
   no photographic detail at all; the classifier never saw such inputs as
   positives, but the explicit std-based rule is cheaper and explains
   itself. The green/white product-shot rule remains only as a FALLBACK
   for if the ONNX gate file is missing/corrupt, so the app never silently
   degrades to "diagnose anything".

Deliberately NOT rejected (documented in README limitations): humans/skin,
documents, complex real-world scenes — the synthetic negative set does not
cover them; they pass the gate and rely on the honest low-confidence path.

Photo-quality warnings (advisory, never blocking): blurry and very dark
leaf photos ARE diagnosed (thresholds below; calibrated on the real test
split so >98% of real leaves raise no warning), but the response carries
Bangla notes asking for a better shot.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import numpy as np
from PIL import Image

# --- trained gate ------------------------------------------------------------
GATE_MODEL_PATH = Path(__file__).resolve().parents[1] / "data" / "plant_guard_model.onnx"

# Chosen for the serving-side held-out evaluation (see
# ml/reports/plant_classifier_metrics.json -> serving_holdout:
# ml/src/evaluate_plant_gate.py): at 0.35 the raw classifier rejects only
# ~0.2-0.6% of real leaves; the assembled gate (strong-leaf override +
# model) passes 99.2% end to end. Lower junk tails flow to the honest
# low-confidence path.
GATE_THRESHOLD = 0.35

# --- heuristic thresholds (calibration data in git history of this file) ------
FLAT_STD_MIN = 3.0        # grayscale std below this = no photographic detail
GREEN_MIN = 0.08          # fraction of vegetation-green pixels (ExG test)
WHITE_MAX = 0.50          # plain-background fraction allowed alongside low green

# --- photo-quality thresholds (calibrated on 80 real test-split leaves) ------
# Laplacian variance of the 320px grayscale thumb; the 1st percentile of real
# leaf photos is ~90-185, and P(leaf) blur warning stays quiet above ~150.
BLUR_LAPVAR_MIN = 150
# Mean brightness of the same thumb; the 10th percentile of real test-split
# leaves is ~46 (PlantVillage-style dark backgrounds), so DARK only fires on
# the genuinely unusable near-black shots, not on dark-backdrop lab photos.
DARK_MEAN_MAX = 50

REJECT_FLAT = (
    "ছবিতে কোনো দৃশ্য নেই (একদম ফাঁকা/একরঙা)। সন্দেহভাজন পাতার একটি স্পষ্ট ছবি "
    "তুলে আবার চেষ্টা করুন।"
)
REJECT_NO_LEAF = (
    "ছবিতে গাছের পাতা ধরা পড়েনি। সন্দেহভাজন পাতাটি কাছ থেকে, দিন-আলোয় তুলুন "
    "(ফসলের ফল/কন্দ, প্লাস্টিক প্যাকেট বা অন্য কোনো বস্তু নয়) — তারপর আবার "
    "স্ক্যান করুন।"
)

WARN_BLUR = (
    "📷 ছবিটি ঝাপসা মনে হচ্ছে (ক্যামেরা নড়েছে বা ফোকাস হয়নি)। সম্ভব হলে কাছ থেকে "
    "আবার তুলুন — স্পষ্ট ছবি হলে রোগ শনাক্তের নির্ভরযোগ্যতা অনেক বাড়ে।"
)
WARN_DARK = (
    "📷 ছবিটি অনেক অন্ধকার। দিন-আলোয় (সকাল/বিকেল) আবার তুললে নির্ণয় অনেক বেশি "
    "নির্ভরযোগ্য হবে।"
)


@dataclass
class PlantStats:
    """Raw measurements, kept for logging/tests rather than user display."""

    green_frac: float
    white_frac: float
    gray_std: float


def _features(img: Image.Image) -> PlantStats:
    """Compute the color/texture statistics the heuristic rules need."""
    small = img.convert("RGB")
    small.thumbnail((256, 256))  # stats are scale-free; saves work
    arr = np.asarray(small, dtype=np.float32)
    r, g, b = arr[..., 0], arr[..., 1], arr[..., 2]

    # Excess-green vegetation index — the standard remote-sensing cue.
    exg = 2.0 * g - r - b
    green_frac = float(((exg > 25.0) & (g > 60.0)).mean())

    mx = arr.max(-1)
    mn = arr.min(-1)
    sat = np.where(mx > 0, (mx - mn) / np.maximum(mx, 1.0), 0.0)
    val = mx / 255.0
    white_frac = float(((sat < 0.12) & (val > 0.75)).mean())

    gray = arr.mean(-1)
    gray_std = float(gray.std())
    return PlantStats(green_frac, white_frac, gray_std)


def _norm_stats(img: Image.Image) -> PlantStats:
    """Color stats on the EXPOSURE-NORMALIZED 128px thumb (same normalization
    as _classifier_features): dark photos get their green structure back."""
    small = img.convert("RGB")
    small.thumbnail((128, 128))
    arr = np.asarray(small, dtype=np.float32)
    vm = float((arr.max(-1) / 255.0).mean())
    if vm < 0.40 and vm > 0.003:
        arr = np.clip(arr * min(0.40 / vm, 12.0), 0, 255)
    r, g, b = arr[..., 0], arr[..., 1], arr[..., 2]
    exg = 2.0 * g - r - b
    green_frac = float(((exg > 25.0) & (g > 60.0)).mean())
    mx = arr.max(-1)
    mn = arr.min(-1)
    sat = np.where(mx > 0, (mx - mn) / np.maximum(mx, 1.0), 0.0)
    white_frac = float(((sat < 0.12) & (mx / 255.0 > 0.75)).mean())
    gray_std = float(arr.mean(-1).std())
    return PlantStats(green_frac, white_frac, gray_std)


# --- trained classifier gate -------------------------------------------------
def _classifier_features(img: Image.Image) -> list[float]:
    """19-feature vector, byte-compatible with training
    (ml/src/train_plant_classifier.py::features). MUST be updated together
    with that file or the gate silently degrades."""
    small = img.convert("RGB")
    small.thumbnail((128, 128))
    if small.size[0] < 32 or small.size[1] < 32:
        pad = Image.new("RGB", (max(small.size[0], 32), max(small.size[1], 32)), (0, 0, 0))
        pad.paste(small, (0, 0))
        small = pad
    arr = np.asarray(small, dtype=np.float32)
    # Exposure normalization — MUST stay byte-identical with training
    # (ml/src/train_plant_classifier.py::features): dark phone shots need
    # their color structure exposed, else the green tests zero out and a
    # dark leaf is indistinguishable from dark junk.
    vm = float((arr.max(-1) / 255.0).mean())
    if vm < 0.40 and vm > 0.003:
        arr = np.clip(arr * min(0.40 / vm, 12.0), 0, 255)
    r, g, b = arr[..., 0], arr[..., 1], arr[..., 2]
    mx = arr.max(-1)
    mn = arr.min(-1)
    val = mx / 255.0
    sat = np.where(mx > 0, (mx - mn) / np.maximum(mx, 1.0), 0.0)
    exg = 2.0 * g - r - b

    green = float(((exg > 25.0) & (g > 60.0)).mean())
    white = float(((sat < 0.12) & (val > 0.75)).mean())
    dark = float((val < 0.18).mean())
    brown = float(((r > g) & (g > b) & (r - b > 40) & (r > 60) & (r < 230) & (sat > 0.15)).mean())
    yellow = float(((r > 0.6 * 255) & (g > 0.55 * 255) & (b < 0.45 * 255) & (sat > 0.2)).mean())

    gray = arr.mean(-1)
    lap = np.zeros_like(gray)
    lap[1:-1, 1:-1] = (
        4 * gray[1:-1, 1:-1]
        - gray[:-2, 1:-1] - gray[2:, 1:-1] - gray[1:-1, :-2] - gray[1:-1, 2:]
    )
    lapm = float(np.abs(lap).mean())
    laps = float(lap.std())

    gy, gx = np.gradient(gray)
    grad = np.hypot(gx, gy)
    grad_mean = float(grad.mean())
    edge_density = float((grad > 20).mean())

    H, W = gray.shape
    bh, bw = max(H // 4, 1), max(W // 4, 1)
    bg_fractions, bw_fractions = [], []
    for i in range(4):
        for j in range(4):
            sl = g[i * bh:(i + 1) * bh, j * bw:(j + 1) * bw]
            slr = r[i * bh:(i + 1) * bh, j * bw:(j + 1) * bw]
            slb = b[i * bh:(i + 1) * bh, j * bw:(j + 1) * bw]
            e = 2.0 * sl - slr - slb
            bg_fractions.append(float(((e > 25.0) & (sl > 60.0)).mean()))
            sw = arr[i * bh:(i + 1) * bh, j * bw:(j + 1) * bw]
            smx = sw.max(-1)
            smn = sw.min(-1)
            ss = np.where(smx > 0, (smx - smn) / np.maximum(smx, 1.0), 0.0)
            sv = smx / 255.0
            bw_fractions.append(float(((ss < 0.12) & (sv > 0.75)).mean()))
    bg_arr = np.asarray(bg_fractions)
    top, bottom = bg_arr[:8].mean(), bg_arr[8:].mean()
    block_green_updown = abs(top - bottom)

    rg = arr[..., 0] - arr[..., 1]
    yb = (arr[..., 0] + arr[..., 1]) / 2.0 - arr[..., 2]
    colorfulness = float(np.hypot(rg.std(), yb.std()) + 0.3 * (np.abs(rg).mean() + np.abs(yb).mean()))

    return [
        green, white, dark, brown, yellow,
        float(sat.mean()), float(sat.std()), float(val.mean()), float(val.std()),
        colorfulness, lapm, laps, edge_density, grad_mean,
        float(bg_arr.mean()), float(bg_arr.max()), float(np.percentile(bg_arr, 75)),
        float(max(bw_fractions)), block_green_updown,
    ]


_session = None
_session_failed = False


def _gate_session():
    """Lazily load the ONNX gate model. Returns None when unavailable."""
    global _session, _session_failed
    if _session is not None or _session_failed:
        return _session
    try:
        import onnxruntime as ort

        _session = ort.InferenceSession(str(GATE_MODEL_PATH), providers=["CPUExecutionProvider"])
    except Exception as exc:  # noqa: BLE001 - gate must never break serving
        import logging

        logging.getLogger(__name__).warning("[plant_guard] gate model unavailable (%s); heuristic fallback active", exc)
        _session_failed = True
        _session = None
    return _session


def _trained_leaf_probability(img: Image.Image) -> float | None:
    """P(plant material) from the trained gate, or None when unavailable."""
    sess = _gate_session()
    if sess is None:
        return None
    feats = np.asarray([_classifier_features(img)], dtype=np.float32)
    out = sess.run(None, {sess.get_inputs()[0].name: feats})
    raw = out[-1]
    row = raw[0]
    p_leaf = row[1] if isinstance(row, dict) else row[-1]
    return float(p_leaf)


# Strong-leaf override (measured on 40 real leaves × 3 quality levels):
# heavily blurred/dark leaf photos score p(leaf) as low as 0.001 because
# blur overlaps the smooth-background negatives, so the classifier alone
# rejects them. But when the exposure-normalized image is overwhelmingly
# vegetation-green AND textured, only unrealistic synthetic junk (green
# gradients, ~6% of the negative set) excites this rule; those "slips"
# then land on the honest low-confidence path, not a fake diagnosis.
STRONG_LEAF_GREEN_MIN = 0.50
STRONG_LEAF_TEXTURAL_MIN = 14.0


def looks_like_leaf(img: Image.Image) -> tuple[bool, str]:
    """Return (ok, message). message is empty when ok, else Bangla guidance."""
    stats = _features(img)

    if stats.gray_std < FLAT_STD_MIN:
        return False, REJECT_FLAT

    # Strong-leaf override — protects bad-camera leaf photos (blur/dark)
    # from the trained gate's blurred-regime blind spot.
    norm = _norm_stats(img)
    if norm.green_frac >= STRONG_LEAF_GREEN_MIN and norm.gray_std >= STRONG_LEAF_TEXTURAL_MIN:
        return True, ""

    p_leaf = _trained_leaf_probability(img)
    if p_leaf is not None:
        if p_leaf < GATE_THRESHOLD:
            return False, REJECT_NO_LEAF
        return True, ""

    # Fallback: the v1 plain-background product-shot rule, only when the
    # trained gate could not run.
    if stats.green_frac < GREEN_MIN and stats.white_frac > WHITE_MAX:
        return False, REJECT_NO_LEAF

    return True, ""


def photo_warnings(img: Image.Image) -> list[str]:
    """Advisory Bangla notes on diagnosable-but-bad photo quality.

    Never blocks: a blurry/dark leaf photo still flows to the model and to
    the honest low-confidence path; these warnings ride along in the
    response so the farmer knows a retake would help.
    """
    small = img.convert("L")
    small.thumbnail((320, 320))
    a = np.asarray(small, dtype=np.float32)

    warnings: list[str] = []
    lap = np.zeros_like(a)
    lap[1:-1, 1:-1] = (
        4 * a[1:-1, 1:-1] - a[:-2, 1:-1] - a[2:, 1:-1] - a[1:-1, :-2] - a[1:-1, 2:]
    )
    if float(lap.var()) < BLUR_LAPVAR_MIN:
        warnings.append(WARN_BLUR)
    if float(a.mean()) < DARK_MEAN_MAX:
        warnings.append(WARN_DARK)
    return warnings
